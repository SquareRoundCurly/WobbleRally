import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const track = await readFile(new URL('src/track.json', root), 'utf8')
const sections = await Promise.all(['race.js', 'ui.js', 'main.js'].map(name => readFile(new URL(`src/${name}`, root), 'utf8')))
await writeFile(new URL('scripts/main.js', root), `// Generated by npm run build. Edit src/, then rebuild.\nconst TRACK = ${track.trim()};\n${sections.join('\n')}\n`)
console.log('Built self-contained Atlas lifecycle script.')
